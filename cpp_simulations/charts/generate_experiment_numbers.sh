#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
DATA_FILE=${1:-"$SCRIPT_DIR/data/improvement_ratios.csv"}
OUT_FILE=${2:-"$SCRIPT_DIR/../../Input_Section/experiment_numbers.tex"}
TICKS=${TICKS:-100000}

format_ticks() {
  case "$1" in
    1000) echo "10^3" ;;
    10000) echo "10^4" ;;
    100000) echo "10^5" ;;
    1000000) echo "10^6" ;;
    *) echo "$1" ;;
  esac
}

mkdir -p "$(dirname "$OUT_FILE")"

awk -F, -v ticks_tex="$(format_ticks "$TICKS")" '
  function mean(value) {
    return sprintf("%.1f", value + 0)
  }
  function ratio(value) {
    return sprintf("%.2f", value + 0)
  }
  function macro(name, value) {
    printf("\\newcommand{\\%s}{%s}\n", name, value)
  }
  NR == 1 {
    for (i = 1; i <= NF; ++i) {
      col[$i] = i
    }
    next
  }
  $1 == 10 {
    found = 1
    opp_unikem_fast = $(col["opp_unikem_fast_mean"])
    agg_unikem_fast = $(col["agg_unikem_fast_mean"])
    agg_unikem_slow = $(col["agg_unikem_slow_mean"])
    opp_rkem_fast = $(col["opp_rkem_fast_mean"])
    agg_rukem_fast = $(col["agg_rukem_fast_mean"])
    agg_rukem_slow = $(col["agg_rukem_slow_mean"])

    unikem_fast_gain = $(col["unikem_fast_gain"])
    unikem_slow_gain = $(col["unikem_slow_gain"])
    rukem_fast_gain = $(col["rukem_fast_gain"])
    rukem_slow_gain = $(col["rukem_slow_gain"])
    aggrukem_fast_gain_over_aggunikem = $(col["aggrukem_fast_gain_over_aggunikem"])
    aggrukem_slow_gain_over_aggunikem = $(col["aggrukem_slow_gain_over_aggunikem"])
  }
  $1 == 15 {
    found_15 = 1
    unikem_fast_gain_15 = $(col["unikem_fast_gain"])
  }
  $1 == 20 {
    found_20 = 1
    unikem_fast_gain_20 = $(col["unikem_fast_gain"])
  }
  END {
    if (!found) {
      print "missing ratio 10 in " FILENAME > "/dev/stderr"
      exit 1
    }
    if (!found_15) {
      print "missing ratio 15 in " FILENAME > "/dev/stderr"
      exit 1
    }
    if (!found_20) {
      print "missing ratio 20 in " FILENAME > "/dev/stderr"
      exit 1
    }

    print "% Generated by cpp_simulations/charts/generate_experiment_numbers.sh."
    print "% Do not edit by hand; regenerate from cpp_simulations/charts/data/improvement_ratios.csv."
    macro("ExpTicks", ticks_tex)
    macro("ExpAggUniFastGainAtTen", ratio(unikem_fast_gain))
    macro("ExpAggUniFastGainAtFifteen", ratio(unikem_fast_gain_15))
    macro("ExpAggUniFastGainAtTwenty", ratio(unikem_fast_gain_20))
    macro("ExpAggUniSlowGainAtTen", ratio(unikem_slow_gain))
    macro("ExpOppRkemAggRukemFastGainAtTen", ratio(rukem_fast_gain))
    macro("ExpOppRkemAggRukemSlowGainAtTen", ratio(rukem_slow_gain))
    macro("ExpAggRukemVsAggUniFastGainAtTen", ratio(aggrukem_fast_gain_over_aggunikem))
    macro("ExpAggRukemVsAggUniSlowRatioAtTen", ratio(aggrukem_slow_gain_over_aggunikem))
    macro("ExpOppUniFastMeanAtTen", mean(opp_unikem_fast))
    macro("ExpAggUniFastMeanAtTen", mean(agg_unikem_fast))
    macro("ExpAggUniSlowMeanAtTen", mean(agg_unikem_slow))
    macro("ExpOppRkemFastMeanAtTen", mean(opp_rkem_fast))
    macro("ExpAggRukemFastMeanAtTen", mean(agg_rukem_fast))
    macro("ExpAggRukemSlowMeanAtTen", mean(agg_rukem_slow))
  }
' "$DATA_FILE" > "$OUT_FILE"

echo "Wrote LaTeX experiment numbers to $OUT_FILE"
